CLOSING_INSTRUCTIONS = [
    ("title", "PACIFIC CREST ESCROW, INC. — CLOSING INSTRUCTIONS"),
    ("", ""),
    ("body", "Date of Instructions: March 5, 2026"),
    ("body", "Escrow No.: ESC-4821-CA          Loan ID # L-2026-0417"),
    ("body", "Borrower: Rowan Delgado"),
    ("body", "Lender: Sierra Home Lending, LLC"),
    ("body", "Property: 2716 Alder Court, Pasadena, CA 91104"),
    ("", ""),
    ("body", "Scheduled signing and closing date: March 12, 2026"),
    ("", ""),
    ("heading", "EXECUTION AND ACKNOWLEDGMENT"),
    ("body", "The Deed of Trust must be executed by the borrower and acknowledged"),
    ("body", "before a notary public prior to disbursement. The executed and"),
    ("body", "acknowledged Deed of Trust will be recorded in the Official Records of"),
    ("body", "Los Angeles County. Escrow may not close until the recorded instrument"),
    ("body", "package is complete."),
    ("", ""),
    ("body", "Return the signed instruction acknowledgment and the notarized document"),
    ("body", "package to Pacific Crest Escrow, Inc. no later than one business day"),
    ("body", "before the scheduled closing date."),
]


def main() -> None:
    cert = build_document(
        "ron-closing",
        "notary-certificate",
        NOTARY_CERTIFICATE,
        "Notary Acknowledgment ESC-4821-CA",
    )
    instructions = build_document(
        "ron-closing",
        "closing-instructions",
        CLOSING_INSTRUCTIONS,
        "Closing Instructions ESC-4821-CA",
    )

    manifest = {
        "id": "ron-closing",
        "title": "California remote online notarization eligibility for a closing",
        "caseId": "case:closing:ESC-4821-CA",
        "ontology": {"ontology": "duly-starter-ron", "version": "0.1.0"},
        "documents": [
            {
                "id": "doc:notary-certificate:ESC-4821-CA:2026-03-12",
                "title": "Notary Acknowledgment (Deed of Trust)",
                **cert,
            },
            {
                "id": "doc:closing-instructions:ESC-4821-CA:2026-03-05",
                "title": "Escrow Closing Instructions",
                **instructions,
            },
        ],
        "facts": [
            "facts/fact-cert-state.json",
            "facts/fact-cert-method.json",
            "facts/fact-instructions-closing-date.json",
        ],
        "rulePack": "rulepacks/notarization-ron-us-states/pack.yaml",
    }

    path = STARTERS / "ron-closing" / "scenario.json"
    path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(STARTERS.parent)}")


if __name__ == "__main__":
    main()
