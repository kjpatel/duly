    ("body", "instrument, and acknowledged to me that they executed the same in their"),
    ("body", "authorized capacity, and that by their signature on the instrument the"),
    ("body", "person, or the entity upon behalf of which the person acted, executed"),
    ("body", "the instrument."),
    ("", ""),
    ("body", "Method of appearance: remote online notarization — the signer appeared"),
    ("body", "before the notary by two-way audio-visual communication technology and"),
    ("body", "was not in the physical presence of the notary."),
