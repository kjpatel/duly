#!/usr/bin/env python3
"""Generate the synthetic ron-closing starter documents.

A California deed-of-trust acknowledgment performed by remote online
audio-visual means on March 12, 2026 — a date on which California's Online
Notarization Act (SB 696, Stats. 2023, ch. 291) is signed law but not yet
operative. Adjudicated today the notarization is not compliant; the same
facts adjudicated at the statute's outside operative date (2030-01-01) flip.

Documents are SYNTHETIC by convention: they live in starters/ and are
generated by this committed script. It reuses the shared helpers from
starters/tools/make_documents.py (render_pdf/rendition_text/build_document)
and writes this scenario's manifest with the actual PDF SHA-256s.

Usage (from the repo root):
    uv run python starters/ron-closing/make_documents.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

STARTERS = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(STARTERS / "tools"))

from make_documents import build_document  # noqa: E402

